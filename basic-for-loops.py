# Basic for loops

# Range(stop)
for i in range(7):
	print(i)
	print("Done!")

# Range(start,stop)
for i in range(2,6):
	print(i)
	print("Done!")

# Range(start,stop,step)
for i in range(1,10,2):
	print(i)
	print("Done!")
	
# Reversing a range using negative step function
for i in range(5,0,-1):
	print(i)
	print ("Done!")

# Reversing a range using reversed( ) function
for i in reversed(range(1,6,1)):
	print(i)
	print("Done!")
