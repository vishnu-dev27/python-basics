#1. Basic Lists (or) Single-dimensional lists

numbers_list = [8,16,24,32]
print(numbers_list)

#2. Accessing Values from a Single-dimensional list

numbers_list = [8,16,24,32]
print(numbers_list[2])

#3. Accessing Negative indexing Values from a Single-dimensional list

numbers_list = [8,16,24,32]
print(numbers_list[-1])

#4. Multi-dimensional lists

my_list1 = [[16,24,32], "Meso soup", [40,48,56]]
print(my_list1)

#5. Accessing Values from a multi-dimensional list

my_list1 = [[16,24,32], "Meso soup", [40,48,56]]
print(my_list1[0][1])


